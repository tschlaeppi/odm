export type MessageKey = keyof (typeof messages)['de']

const STORAGE_KEY = 'odm.locale'

function initialLocale(): Locale {
  const stored = localStorage.getItem(STORAGE_KEY)
  if (stored === 'de' || stored === 'en') return stored
  return navigator.language.toLowerCase().startsWith('de') ? 'de' : 'en'
}

class I18n {
  locale = $state<Locale>(initialLocale())

  constructor() {
    document.documentElement.lang = this.locale
  }

  set(locale: Locale) {
    this.locale = locale
    localStorage.setItem(STORAGE_KEY, locale)
    document.documentElement.lang = locale
  }

  toggle() {
    this.set(this.locale === 'de' ? 'en' : 'de')
  }

  t(key: MessageKey, params?: Record<string, string | number>): string {
    let text: string = messages[this.locale][key]
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.replaceAll(`{${name}}`, String(value))
      }
    }
    return text
  }

  /** Server and agent messages are English; show them in the selected language. */
  server(text: string | null | undefined): string {
    return text ? translateServerMessage(text, this.locale) : ''
  }

  formatDate(iso: string | null): string {
    if (!iso) return '–'
    return new Intl.DateTimeFormat(this.locale, { dateStyle: 'medium', timeStyle: 'short' }).format(new Date(iso))
  }
}

export const i18n = new I18n()
